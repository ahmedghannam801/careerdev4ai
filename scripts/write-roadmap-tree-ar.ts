/**
 * Writes the Arabic entries for the roadmap topic catalogue into the Arabic
 * catalogue the application reads from.
 *
 * The keys are exact English source strings. Generating them from the shared
 * catalogue keeps the translation keys aligned, and replacing the marked
 * section makes this script safe to run more than once.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { ROADMAP_TOPIC_CATALOGUE } from '../shared/roadmapTree.ts';
import { ROADMAP_TOPIC_CATALOGUE_AR } from '../shared/roadmapTreeAr.ts';

const TARGET = 'src/translations/parts/roadmap.ts';
const entries: Array<[string, string]> = [];

for (const seeds of Object.values(ROADMAP_TOPIC_CATALOGUE)) {
  for (const seed of seeds) {
    const arabic = ROADMAP_TOPIC_CATALOGUE_AR[seed.id];
    if (!arabic) {
      console.error(`No Arabic entry for the topic "${seed.id}".`);
      process.exitCode = 1;
      continue;
    }
    entries.push([seed.title, arabic.title]);
    entries.push([seed.description, arabic.description]);
    entries.push([seed.practice.target, arabic.practice]);
  }
}

if (process.exitCode) process.exit(1);

const source = readFileSync(TARGET, 'utf8');
const lineEnding = source.includes('\r\n') ? '\r\n' : '\n';
const closingMarker = `${lineEnding}};`;
const closingIndex = source.lastIndexOf(closingMarker);
if (closingIndex === -1) {
  console.error(`Could not find the end of the catalogue in ${TARGET}.`);
  process.exit(1);
}

const generatedMarker = '  // The roadmap topic catalogue: the title, the explanation and the practice';
let body = source.slice(0, closingIndex);
const previousGeneratedBlock = body.lastIndexOf(generatedMarker);
if (previousGeneratedBlock !== -1) {
  body = body.slice(0, previousGeneratedBlock).replace(/(?:\r?\n)+$/, '');
}
const suffix = source.slice(closingIndex + closingMarker.length);

const block = [
  '  // The roadmap topic catalogue: the title, the explanation and the practice',
  '  // of every topic on the tree. Generated by scripts/write-roadmap-tree-ar.ts,',
  '  // so the keys cannot drift away from the shared catalogue.',
  ...entries.map(([english, arabic]) =>
    `  ${JSON.stringify(english)}:${lineEnding}    ${JSON.stringify(arabic)},`
  ),
].join(lineEnding);

writeFileSync(TARGET, `${body}${lineEnding}${block}${lineEnding}};${suffix}`, 'utf8');
console.log(`Wrote ${entries.length} Arabic entries into ${TARGET}.`);
